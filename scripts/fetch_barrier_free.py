def title(public_pk: str) -> str:
    page = get(f"{PORTAL}/data/{public_pk}/fileData.do").decode("utf-8", "replace")
    m = re.search(r"<title>([^<|]*)", page)
    return m.group(1).strip() if m else public_pk


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    missing = []
    for i, public_pk in enumerate(IDS, 1):
        name = re.sub(r"[\/:*?\"<>|]", "_", title(public_pk))
        try:
            body = download(public_pk)
        except RuntimeError:  # 포털에 첨부 파일이 없는 자료(목록에는 있으나 파일 없음)
            missing.append(name)
            continue
        (OUT / f"{name}.csv").write_bytes(body)
        print(f"{i}/{len(IDS)} {name}")
    print(f"받음 {len(IDS) - len(missing)}개, 파일 없음 {len(missing)}개: {', '.join(missing)}")


if __name__ == "__main__":
    main()
